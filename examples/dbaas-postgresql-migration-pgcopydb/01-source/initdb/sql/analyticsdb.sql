-- analyticsdb: second logical database, two schemas (staging, reporting).
-- Small, but with objects that tend to slip through a migration:
-- UNLOGGED table, materialized view, sequence with an offset.

CREATE SCHEMA staging;
CREATE SCHEMA reporting;

COMMENT ON SCHEMA staging   IS 'Raw data landing zone';
COMMENT ON SCHEMA reporting IS 'Aggregates and views';

-- UNLOGGED: part of pg_dump, ignored by logical replication.
CREATE UNLOGGED TABLE staging.raw_events (
    raw_id      bigserial PRIMARY KEY,
    source      text NOT NULL,
    received_at timestamptz NOT NULL DEFAULT now(),
    payload     jsonb NOT NULL
);
CREATE INDEX raw_events_received_idx ON staging.raw_events (received_at);

CREATE TABLE staging.import_runs (
    run_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at timestamptz NOT NULL DEFAULT now(),
    ended_at   timestamptz,
    row_count  bigint NOT NULL DEFAULT 0,
    ok         boolean
);

CREATE TABLE reporting.daily_sales (
    day          date NOT NULL,
    country      char(2) NOT NULL,
    orders       bigint NOT NULL,
    revenue_cents bigint NOT NULL,
    PRIMARY KEY (day, country)
);

-- Sequence that does not start at 1: check last_value after the migration.
CREATE SEQUENCE reporting.report_no_seq START WITH 500000 INCREMENT BY 7;

CREATE TABLE reporting.reports (
    report_no  bigint PRIMARY KEY DEFAULT nextval('reporting.report_no_seq'),
    title      text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE VIEW reporting.v_revenue_by_country AS
SELECT country, sum(revenue_cents) AS revenue_cents, sum(orders) AS orders
FROM reporting.daily_sales
GROUP BY country;

-- pg_dump stores a materialized view as definition plus a REFRESH step.
-- Check on the target that it is populated.
CREATE MATERIALIZED VIEW reporting.mv_monthly_revenue AS
SELECT date_trunc('month', day)::date AS month,
       country,
       sum(revenue_cents) AS revenue_cents
FROM reporting.daily_sales
GROUP BY 1, 2
WITH NO DATA;

GRANT USAGE ON SCHEMA staging, reporting TO app_rw, app_ro;
GRANT SELECT ON ALL TABLES IN SCHEMA staging, reporting TO app_ro;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA staging, reporting TO app_rw;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA staging, reporting TO app_rw;

ALTER DEFAULT PRIVILEGES IN SCHEMA staging, reporting GRANT SELECT ON TABLES TO app_ro;

-- -------------------------------------------------------------- Seed data --

