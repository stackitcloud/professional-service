INSERT INTO staging.import_runs (started_at, ended_at, row_count, ok)
SELECT now() - (g || ' days')::interval, now() - (g || ' days')::interval + interval '4 min', 200000 / g, g % 9 <> 0
FROM generate_series(1, 30) g;

