-- appdb: OLTP-style example, two schemas (catalog, sales).
-- Deliberately contains the object types that usually cause work in a migration:
-- extension, ENUM, IDENTITY vs. serial, partitioning, GIN/trigram index, trigger, view,
-- default privileges. Bulk data comes later from /opt/pg-source/load-data.sh.

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE SCHEMA catalog;
CREATE SCHEMA sales;

COMMENT ON SCHEMA catalog IS 'Product master data';
COMMENT ON SCHEMA sales   IS 'Orders and events';

-- ---------------------------------------------------------------- catalog --

CREATE TABLE catalog.categories (
    category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL UNIQUE,
    parent_id   integer REFERENCES catalog.categories (category_id)
);

CREATE TABLE catalog.products (
    product_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         text NOT NULL UNIQUE,
    name        text NOT NULL,
    category_id integer NOT NULL REFERENCES catalog.categories (category_id),
    price       numeric(10,2) NOT NULL CHECK (price >= 0),
    attributes  jsonb NOT NULL DEFAULT '{}'::jsonb,
    is_active   boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX products_attributes_gin ON catalog.products USING gin (attributes);
CREATE INDEX products_name_trgm      ON catalog.products USING gin (name gin_trgm_ops);
CREATE INDEX products_category_idx   ON catalog.products (category_id) WHERE is_active;

-- On purpose: classic bigserial instead of IDENTITY, so both variants show up in the dump.
CREATE TABLE catalog.product_reviews (
    review_id  bigserial PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES catalog.products (product_id),
    rating     smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
    title      text,
    body       text,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX reviews_product_idx ON catalog.product_reviews (product_id);
CREATE INDEX reviews_created_idx ON catalog.product_reviews (created_at DESC);

-- ------------------------------------------------------------------ sales --

CREATE TYPE sales.order_status AS ENUM ('pending', 'paid', 'shipped', 'cancelled', 'refunded');

CREATE TABLE sales.customers (
    customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    email       text NOT NULL,
    full_name   text NOT NULL,
    country     char(2) NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX customers_email_lower_uidx ON sales.customers (lower(email));

CREATE TABLE sales.orders (
    order_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES sales.customers (customer_id),
    status      sales.order_status NOT NULL DEFAULT 'pending',
    total_cents bigint NOT NULL DEFAULT 0,
    ordered_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX orders_customer_idx ON sales.orders (customer_id);
CREATE INDEX orders_ordered_idx  ON sales.orders (ordered_at);

CREATE TABLE sales.order_items (
    order_id   bigint NOT NULL REFERENCES sales.orders (order_id) ON DELETE CASCADE,
    line_no    smallint NOT NULL,
    product_id bigint NOT NULL REFERENCES catalog.products (product_id),
    quantity   integer NOT NULL CHECK (quantity > 0),
    unit_cents bigint NOT NULL,
    PRIMARY KEY (order_id, line_no)
);
CREATE INDEX order_items_product_idx ON sales.order_items (product_id);

-- Trigger + function: part of the dump, but a common pitfall for tools that
-- copy table data only (CDC/DMS-style migrations).
CREATE FUNCTION sales.touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER orders_touch_updated_at
    BEFORE UPDATE ON sales.orders
    FOR EACH ROW EXECUTE FUNCTION sales.touch_updated_at();

-- Partitioned table: carries most of the data after load-data.sh.
CREATE SEQUENCE sales.events_event_id_seq AS bigint;

CREATE TABLE sales.events (
    event_id    bigint NOT NULL DEFAULT nextval('sales.events_event_id_seq'),
    customer_id bigint,
    event_type  text NOT NULL,
    payload     jsonb NOT NULL,
    created_at  timestamptz NOT NULL,
    PRIMARY KEY (event_id, created_at)
) PARTITION BY RANGE (created_at);

ALTER SEQUENCE sales.events_event_id_seq OWNED BY sales.events.event_id;

DO $$
DECLARE
    m date;
BEGIN
    FOR m IN SELECT generate_series('2025-01-01'::date, '2025-12-01'::date, '1 month') LOOP
        EXECUTE format(
            'CREATE TABLE sales.events_%s PARTITION OF sales.events FOR VALUES FROM (%L) TO (%L)',
            to_char(m, 'YYYY_MM'), m, m + interval '1 month');
    END LOOP;
END;
$$;

CREATE TABLE sales.events_default PARTITION OF sales.events DEFAULT;
CREATE INDEX events_created_idx ON sales.events (created_at);

CREATE VIEW sales.v_order_totals AS
SELECT o.order_id,
       o.customer_id,
       o.status,
       sum(oi.quantity * oi.unit_cents) AS computed_total_cents,
       count(*)                         AS line_count
FROM sales.orders o
JOIN sales.order_items oi USING (order_id)
GROUP BY o.order_id, o.customer_id, o.status;

-- ------------------------------------------------------------- Privileges --

GRANT USAGE ON SCHEMA catalog, sales TO app_rw, app_ro;
GRANT SELECT ON ALL TABLES IN SCHEMA catalog, sales TO app_ro;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA catalog, sales TO app_rw;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA catalog, sales TO app_rw;

ALTER DEFAULT PRIVILEGES IN SCHEMA catalog, sales GRANT SELECT ON TABLES TO app_ro;
ALTER DEFAULT PRIVILEGES IN SCHEMA catalog, sales GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO app_rw;

