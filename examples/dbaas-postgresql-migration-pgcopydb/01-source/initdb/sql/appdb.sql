INSERT INTO sales.orders (customer_id, status, ordered_at)
SELECT
    1 + (random() * 49999)::bigint,
    (ARRAY['pending','paid','shipped','cancelled','refunded'])[1 + (g % 5)]::sales.order_status,
    '2025-01-01'::timestamptz + (random() * 364) * interval '1 day'
FROM generate_series(1, 100000) g;

INSERT INTO sales.order_items (order_id, line_no, product_id, quantity, unit_cents)
SELECT
    o.order_id,
    l.line_no,
    1 + (random() * 19999)::bigint,
    1 + (random() * 4)::int,
    (random() * 50000)::bigint + 100
FROM sales.orders o
CROSS JOIN LATERAL (
    SELECT generate_series(1, 1 + (o.order_id % 3))::smallint AS line_no
) l;

UPDATE sales.orders o
SET total_cents = t.total
FROM (
    SELECT order_id, sum(quantity * unit_cents) AS total
    FROM sales.order_items GROUP BY order_id
) t
WHERE o.order_id = t.order_id;

